/// <summary>
/// JSON 文件包装器（支持 {"rules": [...]} 格式）。
/// </summary>
internal class RuleFileWrapper
{
    [JsonPropertyName("rules")]
    public List<RuleDefJson> Rules { get; set; } = new();
}

/// <summary>
/// JSON 规则定义的数据传输对象。
/// 与 <see cref="RuleDef"/> 一一对应，支持从 JSON 反序列化。
/// </summary>
internal class RuleDefJson
{
    /// <summary>规则唯一标识。</summary>
    [JsonPropertyName("ruleId")]
    public string RuleId { get; set; } = string.Empty;

    /// <summary>优先级 — 越小越优先。</summary>
    [JsonPropertyName("priority")]
    public int Priority { get; set; }

    /// <summary>规则分类。</summary>
    [JsonPropertyName("category")]
    public string Category { get; set; } = string.Empty;

    /// <summary>条件表达式。</summary>
    [JsonPropertyName("condition")]
    public string Condition { get; set; } = string.Empty;

    /// <summary>条件满足时要调用的脚本 ID。</summary>
    [JsonPropertyName("scriptId")]
    public string ScriptId { get; set; } = string.Empty;

    /// <summary>最低触发等级。</summary>
    [JsonPropertyName("minLevel")]
    public int MinLevel { get; set; }

    /// <summary>最高触发等级。</summary>
    [JsonPropertyName("maxLevel")]
    public int MaxLevel { get; set; }

    /// <summary>限制职业。</summary>
    [JsonPropertyName("requiredClass")]
    public string? RequiredClass { get; set; }

    /// <summary>需要什么物品。</summary>
    [JsonPropertyName("itemRequired")]
    public string? ItemRequired { get; set; }

    /// <summary>规则说明。</summary>
    [JsonPropertyName("description")]
    public string Description { get; set; } = string.Empty;

    /// <summary>传给脚本的参数键值对。</summary>
    [JsonPropertyName("parameters")]
    public Dictionary<string, string>? Parameters { get; set; }

    /// <summary>是否由经验系统自动生成。</summary>
    [JsonPropertyName("autoGenerated")]
    public bool AutoGenerated { get; set; }

    /// <summary>置信度 0~1。自动生成的规则低于阈值时不生效。</summary>
    [JsonPropertyName("confidence")]
    public float Confidence { get; set; } = 1.0f;

    /// <summary>
    /// 转换为 RuleDef 记录。
    /// </summary>
    public RuleDef ToRuleDef() => new(
        this.RuleId,
        this.Priority,
        this.Category,
        this.Condition,
        this.ScriptId,
        this.MinLevel,
        this.MaxLevel,
        this.RequiredClass,
        this.ItemRequired,
        this.Description,
        this.Parameters,
        this.AutoGenerated,
        this.Confidence);
}
