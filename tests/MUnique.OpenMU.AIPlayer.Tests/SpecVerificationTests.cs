    #region Test 3: Dangerous Zones Not Modified

    /// <summary>
    /// Verifies that the AIPlayer assembly does not depend on or contain types
    /// from dangerous zone namespaces: Network/, Packet/, Memory/.
    /// These are protocol-layer concerns that must not be modified by AI logic.
    /// </summary>
    [Test]
    public void DangerousZonesNotModified()
    {
        var assembly = AIPlayerAssembly;
        var violations = new List<string>();

        // 1. Check referenced assemblies for dangerous namespaces
        foreach (var refAssembly in assembly.GetReferencedAssemblies())
        {
            foreach (var dangerousNs in DangerousNamespaces)
            {
                if (refAssembly.Name is not null
                    && refAssembly.Name.StartsWith(dangerousNs, StringComparison.OrdinalIgnoreCase))
                {
                    violations.Add($"Assembly references dangerous zone: {refAssembly.Name}");
                }
            }
        }

        // 2. Check all types in the assembly for dangerous namespace usage
        foreach (var type in assembly.GetTypes())
        {
            foreach (var dangerousNs in DangerousNamespaces)
            {
                if (type.FullName is not null
                    && type.FullName.StartsWith(dangerousNs, StringComparison.OrdinalIgnoreCase))
                {
                    violations.Add($"Type '{type.FullName}' is in a dangerous zone namespace.");
                }
            }
        }

        // 3. Try git log for the dangerous directories (if git is available)
        try
        {
            var process = new Process
            {
                StartInfo = new ProcessStartInfo
                {
                    FileName = "git",
                    Arguments = "log --oneline --all -- 'Network/' 'Packet/' 'Memory/'",
                    WorkingDirectory = Path.Combine(
                        AppContext.BaseDirectory, "..", "..", "..", "..", "..", "..", ".."),
                    RedirectStandardOutput = true,
                    RedirectStandardError = true,
                    UseShellExecute = false,
                    CreateNoWindow = true,
                },
            };

            process.Start();
            var output = process.StandardOutput.ReadToEnd();
            process.WaitForExit(5000);

            if (process.ExitCode == 0 && !string.IsNullOrWhiteSpace(output))
            {
                var commits = output.Split(new[] { '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries);
                violations.AddRange(
                    commits.Select(c => $"Git detects dangerous zone change: {c}"));
            }
        }
        catch
        {
            // git not available — fall back to reflection checks above
        }

        Assert.That(
            violations,
            Is.Empty,
            $"Dangerous zone violations ({violations.Count}):\n{string.Join("\n", violations)}");
    }

