    #region Test 2: Async Naming Convention

    /// <summary>
    /// Verifies that all public methods returning <see cref="Task"/>, <see cref="Task{T}"/>,
    /// <see cref="ValueTask"/>, or <see cref="ValueTask{T}"/> have names ending with "Async".
    /// This follows the standard .NET async naming convention (VSTHRD100 / AsyncNaming).
    /// </summary>
    [Test]
    public void AllAsyncMethodsEndWithAsyncSuffix()
    {
        var assembly = AIPlayerAssembly;
        var violations = new List<string>();

        foreach (var type in assembly.GetExportedTypes())
        {
            foreach (var method in type.GetMethods(BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly))
            {
                if (method.IsSpecialName)
                {
                    continue;
                }

                if (method.DeclaringType == typeof(object))
                {
                    continue;
                }

                var returnType = method.ReturnType;
                bool isAsync = returnType == typeof(Task)
                    || returnType == typeof(ValueTask)
                    || (returnType.IsGenericType && (
                        returnType.GetGenericTypeDefinition() == typeof(Task<>)
                        || returnType.GetGenericTypeDefinition() == typeof(ValueTask<>)));

                if (isAsync && !method.Name.EndsWith("Async", StringComparison.Ordinal))
                {
                    violations.Add($"{type.FullName}.{method.Name}");
                }
            }
        }

        Assert.That(
            violations,
            Is.Empty,
            $"Methods returning Task/ValueTask without 'Async' suffix ({violations.Count}):\n{string.Join("\n", violations)}");
    }

