    #region Helper Methods

    /// <summary>
    /// Generates the XML doc member key for a constructor.
    /// Format: M:Namespace.Type.#ctor(ParamType1,ParamType2)
    /// </summary>
    private static string GetMethodDocKey(ConstructorInfo ctor)
    {
        var paramTypes = ctor.GetParameters()
            .Select(p => GetParameterTypeName(p.ParameterType));
        return $"M:{ctor.DeclaringType?.FullName}.#ctor({string.Join(",", paramTypes)})";
    }

    /// <summary>
    /// Generates the XML doc member key for a method.
    /// Format: M:Namespace.Type.MethodName(ParamType1,ParamType2)
    /// </summary>
    private static string GetMethodDocKey(MethodInfo method)
    {
        var paramTypes = method.GetParameters()
            .Select(p => GetParameterTypeName(p.ParameterType));
        return $"M:{method.DeclaringType?.FullName}.{method.Name}({string.Join(",", paramTypes)})";
    }

    /// <summary>
    /// Gets the XML doc-compatible parameter type name.
    /// </summary>
    private static string GetParameterTypeName(Type type)
    {
        if (type.IsGenericType)
        {
            var genericDef = type.GetGenericTypeDefinition().FullName;
            if (genericDef is null)
            {
                return type.FullName ?? type.Name;
            }

            // Strip backtick count from generic type name
            var genericBaseName = genericDef[..genericDef.IndexOf('`')];
            var typeArgs = type.GetGenericArguments()
                .Select(GetParameterTypeName);
            return $"{genericBaseName}{{{string.Join(",", typeArgs)}}}";
        }

        return type.FullName ?? type.Name;
    }

