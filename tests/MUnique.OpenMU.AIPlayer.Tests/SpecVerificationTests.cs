    #region Test Infrastructure: TestGridNetwork

    /// <summary>
    /// A minimal <see cref="BaseGridNetwork"/> implementation for testing.
    /// Caches <see cref="Node"/> instances by position so that
    /// the PathFinder can track Open/Closed status across calls.
    /// </summary>
    private sealed class TestGridNetwork : BaseGridNetwork
    {
        private readonly Dictionary<int, Node> _nodes = new();

        /// <summary>
        /// Initializes a new instance of the <see cref="TestGridNetwork"/> class.
        /// </summary>
        /// <param name="allowDiagonals">If set to <c>true</c>, diagonal movement is allowed.</param>
        public TestGridNetwork(bool allowDiagonals = true)
            : base(allowDiagonals)
        {
        }

        /// <inheritdoc />
        public override Node? GetNodeAt(Point position)
        {
            var key = (position.Y << 8) + position.X;
            if (!this._nodes.TryGetValue(key, out var node))
            {
                node = new Node
                {
                    Position = position,
                    Status = NodeStatus.Undefined,
                };
                this._nodes[key] = node;
            }

            return node;
        }

        /// <inheritdoc />
        public override bool Prepare(Point start, Point end, byte[,] grid, bool includeSafezone)
        {
            this._nodes.Clear();
            return base.Prepare(start, end, grid, includeSafezone);
        }
    }

    #endregion
