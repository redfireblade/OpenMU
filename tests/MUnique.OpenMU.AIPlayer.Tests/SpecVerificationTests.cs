    #region Test 1: XML Documentation Completeness

    /// <summary>
    /// Verifies that all public types in the AIPlayer assembly have XML documentation comments.
    /// Loads the XML doc file generated by the build and checks each exported type for a matching member entry.
    /// </summary>
    [Test]
    public void AllPublicTypesAndMethodsHaveXmlDocs()
    {
        var assembly = AIPlayerAssembly;
        var xmlPath = Path.ChangeExtension(assembly.Location, ".xml");

        if (!File.Exists(xmlPath))
        {
            Assert.Inconclusive(
                $"XML documentation file not found at: {xmlPath}. " +
                "Build with <DocumentationFile> or <GenerateDocumentationFile> enabled in the AIPlayer project.");
            return;
        }

        var doc = XDocument.Load(xmlPath);
        var documentedMembers = doc.Root?
            .Element("members")?
            .Elements("member")
            .Select(m => m.Attribute("name")?.Value)
            .Where(v => v is not null)
            .ToHashSet()! ?? new HashSet<string?>();

        var violations = new List<string>();

        foreach (var type in assembly.GetExportedTypes().OrderBy(t => t.FullName))
        {
            var typeDocKey = $"T:{type.FullName}";
            if (!documentedMembers.Contains(typeDocKey))
            {
                violations.Add($"Type '{type.FullName}' is missing XML documentation.");
            }

            // Check constructors
            foreach (var ctor in type.GetConstructors(BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static))
            {
                var ctorDocKey = GetMethodDocKey(ctor);
                if (!documentedMembers.Contains(ctorDocKey))
                {
                    violations.Add($"  Constructor '{type.FullName}(...)' is missing XML documentation.");
                }
            }

            // Check methods (skip property get/set accessors and compiler-generated methods)
            foreach (var method in type.GetMethods(BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly))
            {
                if (method.IsSpecialName)
                {
                    continue;
                }

                if (method.DeclaringType == typeof(object))
                {
                    continue;
                }

                var methodDocKey = GetMethodDocKey(method);
                if (!documentedMembers.Contains(methodDocKey))
                {
                    violations.Add($"  Method '{type.FullName}.{method.Name}' is missing XML documentation.");
                }
            }

            // Check properties
            foreach (var prop in type.GetProperties(BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly))
            {
                var propDocKey = $"P:{prop.DeclaringType?.FullName}.{prop.Name}";
                if (!documentedMembers.Contains(propDocKey))
                {
                    violations.Add($"  Property '{type.FullName}.{prop.Name}' is missing XML documentation.");
                }
            }

            // Check events
            foreach (var evt in type.GetEvents(BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly))
            {
                var evtDocKey = $"E:{evt.DeclaringType?.FullName}.{evt.Name}";
                if (!documentedMembers.Contains(evtDocKey))
                {
                    violations.Add($"  Event '{type.FullName}.{evt.Name}' is missing XML documentation.");
                }
            }
        }

        Assert.That(
            violations,
            Is.Empty,
            $"Found {violations.Count} undocumented public API member(s):\n{string.Join("\n", violations.Take(100))}");
    }

